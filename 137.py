n = int(input("Введите число: ")) # виведення числа від користувача
last_digit = n % 10 # вимірювання останньої цифри числа
if last_digit == 5: # умова перевірки, чи дорівнює остання цифра числа 5
    print("True") # виведення повідомлення, що остання цифра числа дорівнює 5
else:
    print("False")  # виведення повідомлення, що остання цифра числа не дорівнює 5
