n = int(input("Введіть число n: "))

for i in range(1, n + 1): # Перебираємо всі числа від 1 до n

    count = 0 # Лічильник дільників поточного числа

    for j in range(1, i + 1): # Перевіряємо числа від 1 до i

        if i % j == 0: # Якщо i ділиться на j без остачі

            count += 1 # Збільшуємо кількість дільників на 1

    print(str(i) + "+" * count) # Виводимо число та відповідну кількість +
